num_str = "123.45"
# string containing numeric characters
float_val = float(num_str)
# converts the string to a floating point number
int_val = int(float(num_str))
# converts the float value to an integer
print("Original String:", num_str)
# displays original string
print("Parsed Float:", float_val)
# displays parsed float
print("Parsed Integer:", int_val)
# displays parsed integer
