#  List Indexing
# demonstrates how to access elements from a list using indices.
# lists, zero-based positive indexing, negative indexing (-1)
# create a list containing four colors
color_list = ["Red", "Green", "White", "Black"]
# access element at index 1 (the second item: "Green")
print("First color :", color_list[1])
# access element at index -1 (the last item: "Black")
print("Last color :", color_list[-1])