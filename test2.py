# /reverse full name 
# /accepts first and last name from user and prints them in reverse and original order.
# /input() for string input, print() with multiple arguments
# /take the first name from user
first = input("Enter first name: ")
# /take the last name from user
last = input("Enter last name: ")
# /print in reverse order (last name first name)
print(last, first)
# /print in normal order (first name last name)
print(first, last)